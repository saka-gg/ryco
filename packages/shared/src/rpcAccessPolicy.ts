/** Unclassified methods are mutations: delivery uncertainty fails closed. */
export function rpcDeliveryEffectFor(method: string): RpcDeliveryEffect {
  return Object.hasOwn(RPC_DELIVERY_EFFECT_POLICY, method)
    ? RPC_DELIVERY_EFFECT_POLICY[method as RpcMethod]
    : "mutation";
}

const ROLE_ORDER: Readonly<Record<RelayEffectiveRole, number>> = {
  viewer: 1,
  operator: 2,
  owner: 3,
};

export function hostedRoleAllows(
  role: RelayEffectiveRole | null,
  method: string,
  roleStateFresh = true,
): boolean {
  if (!role || !roleStateFresh) return false;
  const required = rpcAccessFor(method);
  if (required === "authenticated" || required === "direct_owner") return false;
  return ROLE_ORDER[role] >= ROLE_ORDER[required];
}
