export function rpcAccessFor(method: string): RpcAccess {
  if (!Object.hasOwn(RPC_ACCESS_POLICY, method)) {
    throw new Error("RPC method has no explicit access classification.");
  }
  return RPC_ACCESS_POLICY[method as RpcMethod];
}

/**
 * What a lost response means for each method — an effect classification, kept
 * apart from the access tiers above on purpose: file, VCS, and source-control
 * reads are operator-tier, so a tier says nothing about whether a request
 * changed anything.
 *
 * - `read` observes node state, or refreshes derived state the node would
 *   regenerate anyway. Losing or repeating one is harmless, so a dropped relay
 *   never leaves its delivery uncertain.
 * - `receipted` changes node state at most once per client-supplied id, and the
 *   node enforces that with a persisted receipt it consults before executing.
 *   Only these may be replayed — unchanged, id included — after a reconnect.
 * - `mutation` is everything else. Its delivery is uncertain whenever the relay
 *   drops before a response, and it is never replayed automatically.
 */
export type RpcDeliveryEffect = "read" | "receipted" | "mutation";

